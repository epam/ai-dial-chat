import {
  IconFile,
  IconFileTypeBmp,
  IconFileTypeCss,
  IconFileTypeCsv,
  IconFileTypeDoc,
  IconFileTypeDocx,
  IconFileTypeHtml,
  IconFileTypeJpg,
  IconFileTypeJs,
  IconFileTypeJsx,
  IconFileTypePdf,
  IconFileTypePhp,
  IconFileTypePng,
  IconFileTypePpt,
  IconFileTypeRs,
  IconFileTypeSql,
  IconFileTypeSvg,
  IconFileTypeTs,
  IconFileTypeTsx,
  IconFileTypeTxt,
  IconFileTypeVue,
  IconFileTypeXls,
  IconFileTypeXml,
  IconFileTypeZip,
  IconMusic,
  IconPhoto,
  IconVideo,
} from '@tabler/icons-react';
import { describe, expect, it } from 'vitest';
import { getAttachmentIcon } from '../attachment';

describe('getAttachmentIcon', () => {
  it.each([
    ['image/jpeg', IconFileTypeJpg],
    ['image/png', IconFileTypePng],
    ['image/svg+xml', IconFileTypeSvg],
    ['image/bmp', IconFileTypeBmp],
    ['image/gif', IconPhoto],
    ['video/mp4', IconVideo],
    ['audio/mpeg', IconMusic],
    ['application/pdf', IconFileTypePdf],
    ['application/msword', IconFileTypeDoc],
    [
      'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      IconFileTypeDocx,
    ],
    ['application/vnd.ms-powerpoint', IconFileTypePpt],
    [
      'application/vnd.openxmlformats-officedocument.presentationml.presentation',
      IconFileTypePpt,
    ],
    ['application/vnd.ms-excel', IconFileTypeXls],
    [
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      IconFileTypeXls,
    ],
    ['application/zip', IconFileTypeZip],
    ['application/vnd.rar', IconFileTypeZip],
    ['application/x-7z-compressed', IconFileTypeZip],
    ['application/gzip', IconFileTypeZip],
    ['application/x-tar', IconFileTypeZip],
    ['text/csv', IconFileTypeCsv],
    ['text/plain', IconFileTypeTxt],
    ['text/html', IconFileTypeHtml],
    ['application/xhtml+xml', IconFileTypeHtml],
    ['application/xml', IconFileTypeXml],
    ['application/sql', IconFileTypeSql],
    ['text/javascript', IconFileTypeJs],
    ['text/jsx', IconFileTypeJsx],
    ['text/typescript', IconFileTypeTs],
    ['text/tsx', IconFileTypeTsx],
    ['text/css', IconFileTypeCss],
    ['text/x-php', IconFileTypePhp],
    ['text/x-rustsrc', IconFileTypeRs],
    ['text/x-vue', IconFileTypeVue],
    ['application/octet-stream', IconFile],
    ['', IconFile],
  ])('returns the expected icon for %s', (contentType, expected) => {
    expect(getAttachmentIcon(contentType)).toBe(expected);
  });
});
