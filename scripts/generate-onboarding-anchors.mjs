#!/usr/bin/env node
//
// Generates docs/onboarding-anchors.md — the catalog of elements an
// ONBOARDING_HINTS entry can point at through its `target`.
//
// The catalog data lives in
// apps/chat/src/components/OnboardingHints/onboarding-anchors.json, next to the
// resolvers that find each element. A unit test keeps that file in step with
// the OnboardingHintTarget enum chat-api accepts; `--check` keeps this document
// in step with the file.
//
// Usage:
//   node scripts/generate-onboarding-anchors.mjs          # write the doc
//   node scripts/generate-onboarding-anchors.mjs --check  # fail if it is stale

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import prettier from 'prettier';

const SOURCE = 'apps/chat/src/components/OnboardingHints/onboarding-anchors.json';
const OUTPUT = 'docs/onboarding-anchors.md';

const escapeCell = (value) => value.replaceAll('|', '\\|');

const render = () => {
  const anchors = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const rows = anchors.map(
    ({ target, page, element, lookup }) =>
      `| \`${target}\` | ${escapeCell(page)} | ${escapeCell(element)} | ${escapeCell(lookup)} |`,
  );
  /* One hint per anchor, so an operator can paste the whole catalog into
   * .env and walk every anchor; titles reuse the catalog's element column. */
  const hints = anchors.map(({ target, page, element }) => ({
    id: target,
    target,
    title: element,
    description: page,
  }));
  return [
    '# Onboarding anchors',
    '',
    'The elements an `ONBOARDING_HINTS` entry can point at. Each hint names one',
    'of these as its `target`; chat-api drops an entry with any other value.',
    '',
    `> Generated by \`scripts/generate-onboarding-anchors.mjs\` from`,
    `> [\`${SOURCE}\`](../${SOURCE}). Edit that file and run`,
    '> `npm run docs:onboarding-anchors`; `npm run validate:docs` fails when this',
    '> page is stale.',
    '',
    'The chat finds each element the way assistive technology sees it — by role',
    'and accessible name, translated into the current language — and only when',
    'it is on screen: it has a box, sits outside an `inert` subtree and is not',
    '`visibility: hidden`. A hint belongs to the pages its `pages` member',
    'names (`home`, `projects`, `scheduled-tasks`, `catalog`, `file-manager`,',
    '`settings`, `usage`, `editors`), or to `home` when it names none. On',
    'each page the tour shows the hints of that page whose elements are on',
    'screen and keeps the rest until their elements appear. The Page column',
    'below says where each anchor is; set `pages` to match it.',
    '',
    '## Seeing the anchors on a page',
    '',
    'Open any chat page with `?onboarding-anchors` in the URL (for example',
    '`/catalog?onboarding-anchors`). Instead of the hints, the chat outlines',
    'every anchor on screen with its `target` name and lists, in a panel at the',
    'bottom corner, the anchors that page does not render. The page stays',
    'usable, so you can open the sidebar or switch tabs and watch the list',
    'change. The view stays on while you follow links in the app; press',
    '"Close anchor view" in the panel, or reload the page without the',
    'parameter, to turn it off.',
    '',
    '## Example with every anchor',
    '',
    'One hint per anchor, titled after the element it points at, on one line as',
    '`.env` needs it. Set it in `apps/chat-api/.env.local`, restart chat-api,',
    'and clear the seen ids (`seenOnboardingHints` in local storage) to walk',
    'every anchor again.',
    '',
    '```sh',
    `ONBOARDING_HINTS=${JSON.stringify(hints)}`,
    '```',
    '',
    '## Anchors',
    '',
    '| `target` | Page | What is highlighted | How the chat finds it |',
    '| -------- | ---- | ------------------- | --------------------- |',
    ...rows,
    '',
    '## Adding an anchor',
    '',
    'Config Studio manages the same tour as `onboarding.hints`, whose schema',
    'lists exactly these targets. A new anchor changes that list, so Config',
    'Studio editors can use it only after a new minor version of the managed',
    'configuration schema is exported and uploaded (see',
    '[Managed configuration schema](managed-config-schema.md#versioning)).',
    'Until then, only `ONBOARDING_HINTS` can point at it.',
    '',
    'A renamed control or a changed role silently stops its anchor from',
    'resolving. `apps/chat/src/components/OnboardingHints/tests/onboarding-targets.spec.tsx`',
    'covers every resolver against fixture markup.',
    '',
  ].join('\n');
};

/* Formatted like every other doc, so a prettier pass never makes it stale. */
const rendered = await prettier.format(render(), {
  ...(await prettier.resolveConfig(OUTPUT)),
  filepath: OUTPUT,
});

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== rendered) {
    console.error(
      `${OUTPUT} is out of date with ${SOURCE}.\n` +
        'Run "npm run docs:onboarding-anchors" and commit the result.',
    );
    process.exit(1);
  }
  console.log(`${OUTPUT} matches ${SOURCE}.`);
} else {
  writeFileSync(OUTPUT, rendered);
  console.log(`Wrote ${OUTPUT}`);
}
