#!/usr/bin/env node
//
// Generates docs/onboarding-anchors.md — the catalog of elements an
// ONBOARDING_HINTS entry can point at through its `target`.
//
// The catalog data lives in
// apps/chat/src/components/OnboardingHints/onboarding-anchors.json, next to the
// resolvers that find each element. A unit test keeps that file in step with
// the OnboardingHintTarget enum chat-api accepts; `--check` keeps this document
// in step with the file.
//
// Usage:
//   node scripts/generate-onboarding-anchors.mjs          # write the doc
//   node scripts/generate-onboarding-anchors.mjs --check  # fail if it is stale

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import prettier from 'prettier';

const SOURCE =
  'apps/chat/src/components/OnboardingHints/onboarding-anchors.json';
const OUTPUT = 'docs/onboarding-anchors.md';

const escapeCell = (value) => value.replaceAll('|', '\\|');

const render = () => {
  const anchors = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const rows = anchors.map(
    ({ target, page, element, lookup }) =>
      `| \`${target}\` | ${escapeCell(page)} | ${escapeCell(element)} | ${escapeCell(lookup)} |`,
  );
  return [
    '# Onboarding anchors',
    '',
    'The elements an `ONBOARDING_HINTS` entry can point at. Each hint names one',
    'of these as its `target`; chat-api drops an entry with any other value.',
    '',
    `> Generated by \`scripts/generate-onboarding-anchors.mjs\` from`,
    `> [\`${SOURCE}\`](../${SOURCE}). Edit that file and run`,
    '> `npm run docs:onboarding-anchors`; `npm run validate:docs` fails when this',
    '> page is stale.',
    '',
    'The chat finds each element the way assistive technology sees it — by role',
    'and accessible name, translated into the current language — and only when',
    'it is on screen: it has a box, sits outside an `inert` subtree and is not',
    '`visibility: hidden`. A hint whose element is not on screen waits:',
    '',
    '- **Tour** (`ONBOARDING_HINTS_MODE=tour`) — the tour shows the hints whose',
    '  elements are on screen and keeps the rest for a page that renders them.',
    '- **Beacons** (`ONBOARDING_HINTS_MODE=beacons`) — a beacon appears as soon',
    '  as its element is rendered.',
    '',
    '| `target` | Page | What is highlighted | How the chat finds it |',
    '| -------- | ---- | ------------------- | --------------------- |',
    ...rows,
    '',
    'A renamed control or a changed role silently stops its anchor from',
    'resolving. `apps/chat/src/components/OnboardingHints/tests/onboarding-targets.spec.tsx`',
    'covers every resolver against fixture markup.',
    '',
  ].join('\n');
};

/* Formatted like every other doc, so a prettier pass never makes it stale. */
const rendered = await prettier.format(render(), {
  ...(await prettier.resolveConfig(OUTPUT)),
  filepath: OUTPUT,
});

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== rendered) {
    console.error(
      `${OUTPUT} is out of date with ${SOURCE}.\n` +
        'Run "npm run docs:onboarding-anchors" and commit the result.',
    );
    process.exit(1);
  }
  console.log(`${OUTPUT} matches ${SOURCE}.`);
} else {
  writeFileSync(OUTPUT, rendered);
  console.log(`Wrote ${OUTPUT}`);
}
